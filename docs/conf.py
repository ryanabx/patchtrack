"""Sphinx configuration for https://ryanabx.github.io/patchtrack.

The command reference is generated from the code: each command's page is
its docstring and options, read from patchtrack.cli.build_parser() by
sphinx-argparse. The pages under commands/ are written at build time, so a
new command gets a page without anyone remembering to add one.
"""

import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "src"))

from patchtrack import __version__, cli  # noqa: E402

project = "patchtrack"
author = "Ryan Brue"
copyright = "2026, Ryan Brue"
release = version = __version__

extensions = ["sphinx.ext.autodoc", "sphinxarg.ext"]
html_theme = "sphinx_rtd_theme"
html_title = f"patchtrack {version}"
html_baseurl = cli.DOCS_URL + "/"
html_theme_options = {"navigation_depth": 2}
html_context = {"display_github": True, "github_user": "ryanabx", "github_repo": "patchtrack",
                "github_version": "main", "conf_py_path": "/docs/"}
highlight_language = "none"
master_doc = "index"
exclude_patterns = ["_build"]


def _write(path, text):
    """Write only when the content changes, so Sphinx does not rebuild for nothing."""
    if not os.path.exists(path) or open(path).read() != text:
        with open(path, "w") as f:
            f.write(text)


def command_pages():
    parser = cli.build_parser()
    sub = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    helps = {a.dest: a.help for a in sub._choices_actions}
    out = os.path.join(HERE, "commands")
    os.makedirs(out, exist_ok=True)
    names = list(sub.choices)
    for name in names:
        title = f"patchtrack {name}"
        _write(os.path.join(out, f"{name}.rst"),
               f":github_url: https://github.com/ryanabx/patchtrack/blob/main/src/patchtrack/cli.py\n\n"
               f"{title}\n{'=' * len(title)}\n\n"
               f"..\n   Generated by docs/conf.py from patchtrack.cli; edit the docstring of cmd_{name}.\n\n"
               f".. argparse::\n   :module: patchtrack.cli\n   :func: build_parser\n"
               f"   :prog: patchtrack\n   :path: {name}\n")
    rows = "\n".join(f"   * - :doc:`{n}`\n     - {helps.get(n, '')}" for n in names)
    _write(os.path.join(out, "index.rst"),
           "Commands\n========\n\n"
           "..\n   Generated by docs/conf.py from patchtrack.cli.\n\n"
           "Every command takes ``--db`` and ``--config`` before its name, and ``-h`` after it.\n\n"
           f".. list-table::\n   :widths: 1 3\n\n{rows}\n\n"
           ".. toctree::\n   :hidden:\n\n" + "\n".join(f"   {n}" for n in names) + "\n")


command_pages()
